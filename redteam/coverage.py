"""The table of threats and what covers each one (docs/threat-coverage.md, ADR-020).

    uv run python -m redteam.coverage

It reads the threat model, the test names and the attack corpus. A test counts for a threat
when its name says so, as in test_t5_new_recipient_requires_explicit_approval. A threat with
neither a test nor an attack needs a written reason in coverage_reasons.json, and
tests/test_threat_coverage.py keeps all of this true, so a new threat cannot be forgotten.

This says what is checked, not that it passes: the tests and attacks report that themselves.
"""

import json
import re
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
THREAT_MODEL = ROOT / "docs" / "02-threat-model.md"
ATTACKS = Path(__file__).with_name("attacks.json")
REASONS = Path(__file__).with_name("coverage_reasons.json")
TABLE = ROOT / "docs" / "threat-coverage.md"

TEST_ROOTS = ("services", "packages", "tests", "web/src")
TEST_SUFFIXES = {".py", ".ts", ".tsx"}
# Not real test names: this file and its own test talk about the naming rule.
EXCLUDED = {"coverage.py", "test_threat_coverage.py"}

_THREAT = re.compile(r"^\s*\d+[.)]\s*\*\*([TE]\d+) — (.+?)\*\*", re.M)
_TEST_NAME = re.compile(r"\btest_([te]\d+)_\w+")


@dataclass(frozen=True)
class Row:
    threat: str
    title: str
    tests: int
    attacks: int
    reason: str

    @property
    def covered(self) -> bool:
        return bool(self.tests or self.attacks or self.reason)


def threats() -> dict[str, str]:
    return dict(_THREAT.findall(THREAT_MODEL.read_text(encoding="utf-8")))


def named_tests() -> dict[str, set[str]]:
    found: dict[str, set[str]] = {}
    for root in TEST_ROOTS:
        for path in sorted((ROOT / root).rglob("*")):
            ignored = "node_modules" in path.parts or path.name in EXCLUDED
            if ignored or path.suffix not in TEST_SUFFIXES or not path.is_file():
                continue
            for match in _TEST_NAME.finditer(path.read_text(encoding="utf-8")):
                found.setdefault(match[1].upper(), set()).add(match[0])
    return found


def reasons() -> dict[str, str]:
    data: dict[str, str] = json.loads(REASONS.read_text(encoding="utf-8"))["reasons"]
    return data


def rows() -> list[Row]:
    tests = named_tests()
    attacks = json.loads(ATTACKS.read_text(encoding="utf-8"))["attacks"]
    written = reasons()
    return [
        Row(
            threat,
            title,
            len(tests.get(threat, ())),
            sum(attack["threat"] == threat for attack in attacks),
            written.get(threat, ""),
        )
        for threat, title in sorted(threats().items(), key=_order)
    ]


def _order(item: tuple[str, str]) -> tuple[bool, int]:
    # Attacks first, then failures, each by number.
    return item[0].startswith("E"), int(item[0][1:])


def render(table: list[Row]) -> str:
    lines = [
        "# Threat coverage",
        "",
        "Generated by `uv run python -m redteam.coverage` from the threat model, the test names",
        "and the attack corpus. Do not edit by hand. CI fails if it is out of date, or if a threat",
        "has neither a test, an attack nor a written reason (ADR-020).",
        "",
        "This table says what is checked. Whether it passes is reported by CI.",
        "",
        "| ID | Threat | Tests | Attacks | Why not tested |",
        "|---|---|---|---|---|",
    ]
    for row in table:
        tests, attacks = row.tests or "", row.attacks or ""
        lines.append(f"| {row.threat} | {row.title} | {tests} | {attacks} | {row.reason} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    TABLE.write_text(render(rows()), encoding="utf-8")


if __name__ == "__main__":
    main()
